const mongoose = require('mongoose');

const otpSchema = new mongoose.Schema({
  email: {
    type: String,
    required: true,
    trim: true,
    lowercase: true
  },
  otp: {
    type: String,
    required: true
  },
  createdAt: {
    type: Date,
    default: Date.now,
    expires: 300   // Document auto-deletes 300 seconds (5 minutes) after creation
  }
});

module.exports = mongoose.model('Otp', otpSchema);
